namespace Atom.Net.Tls.Extensions;

/// <summary>
/// trust_anchors (0xCA34) — список корней, которым клиент доверяет.
/// </summary>
/// <remarks>
/// Черновик TLS Trust Anchor Negotiation: клиент перечисляет идентификаторы корневых
/// сертификатов из собственного хранилища, чтобы сервер прислал ту цепочку, которую клиент
/// способен построить. Chromium отправляет расширение начиная со 143-й версии, и его отсутствие
/// меняет ПЕРВУЮ часть JA4 — количество расширений: замер 2026-09-09 дал у браузера
/// <c lang="text">t13d1517h2</c>, а у нас <c lang="text">t13d1516h2</c> при полном совпадении
/// шифров, групп и отпечатка HTTP/2.
///
/// Содержимое — снимок Chrome Root Store конкретной сборки, а не вычисляемая величина: набор
/// корней задан браузеру списком, и построить его из системного хранилища нельзя — оно другое.
/// Поэтому список хранится байтами ровно так, как его отдаёт браузер, и обновляется тем же
/// способом, каким снят: см. заметки о снятии отпечатка через tls.peet.ws.
/// </remarks>
public sealed class TrustAnchorsTlsExtension : TlsExtension
{
