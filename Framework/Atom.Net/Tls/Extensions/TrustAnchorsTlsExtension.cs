    /// <inheritdoc/>
    public override ushort Id { get; set; } = 0xCA34;

    /// <inheritdoc/>
    public override int Size => 2 + 2 + ChromeTrustAnchors.Length;

    /// <inheritdoc/>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public override void Write(Span<byte> buffer, ref int offset)
    {
        BinaryPrimitives.WriteUInt16BigEndian(buffer[offset..], Id);
        offset += 2;

        BinaryPrimitives.WriteUInt16BigEndian(buffer[offset..], (ushort)ChromeTrustAnchors.Length);
        offset += 2;

        ChromeTrustAnchors.CopyTo(buffer[offset..]);
        offset += ChromeTrustAnchors.Length;
    }

    /// <inheritdoc/>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public override void Reset()
    {
        Id = 0xCA34;
        base.Reset();
    }
}
