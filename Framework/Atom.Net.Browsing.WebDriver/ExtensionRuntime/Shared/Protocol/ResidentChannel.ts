/**
 * Имя события-рандеву для скрипта-резидента главного мира.
 *
 * Резидент нужен, чтобы повторные внедрения скрипта и фоновые команды находили уже установленное
 * состояние подмены окружения. Раньше точкой встречи служили именованные свойства window
 * (__atomTabContext, __atomSyncDocumentCookieHeader и другие) — их видно из страницы простым
 * перечислением свойств, то есть автоматика объявляла о себе сама. Событие такого недостатка
 * лишено: перечислить обработчики событий страничный скрипт не может.
 *
 * Имя выводим из идентификатора сеанса детерминированно — сам идентификатор в страницу не
 * попадает, а результат выглядит как обычный идентификатор приложения, а не служебное имя.
 */
export function deriveResidentChannelName(sessionId: string): string {
    let hash = 0x811c9dc5;
    for (let index = 0; index < sessionId.length; index++) {
        hash ^= sessionId.charCodeAt(index);
        hash = Math.imul(hash, 0x01000193) >>> 0;
    }

    return 'e' + hash.toString(16).padStart(8, '0');
}
