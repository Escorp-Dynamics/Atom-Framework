import { installIdentityInMainWorld, installIdentityInWorker } from './Background/Identity/MainWorldIdentity';
import type { TabContextEnvelope } from './Shared/Protocol';

/**
 * Ранняя подмена личности: контент-скрипт основного мира, объявленный на `document_start` и
 * `all_frames`.
 *
 * Зачем он нужен помимо динамического внедрения из фона. Фон ставит подмену по событию
 * `webNavigation.onCommitted`, то есть АСИНХРОННО, и замер показал, что этого не хватает:
 * в верхнем документе к моменту установки уже `readyState=interactive` и два исполненных скрипта
 * (опаздываем ВСЕГДА), а во фрейме проверки Cloudflare — `scripts=1` в половине случаев. Любой
 * такой опередивший нас скрипт успевает прочитать НАСТОЯЩЕЕ окружение машины, и тогда внутри
 * одного документа наблюдаются две разные личности — признак подделки более явный, чем честный
 * профиль.
 *
 * Этот скрипт внедряет САМ браузер, до любого кода документа и в каждый фрейм, включая ещё не
 * созданные. Поэтому гонка устраняется конструктивно, а не статистически.
 *
 * Профиль сюда кладёт отдельный файл `identity.profile.js`, который создаётся при материализации
 * расширения под конкретный запуск браузера и объявлен в манифесте ПЕРЕД этим файлом. Держать
 * профиль отдельным файлом надёжнее подстановки в текст бандла: не нужно ни экранирование, ни
 * поиск плейсхолдера в собранном коде, а порядок исполнения гарантирован манифестом.
 *
 * Динамическое внедрение из фона при этом остаётся: оно обслуживает СМЕНУ профиля на лету
 * (брокер меняет настройки без пересоздания браузера), которую запечённый файл отразить не может.
 */
const identityHost = globalThis as typeof globalThis & {
    __ATOM_IDENTITY_PROFILE?: TabContextEnvelope | null;
};

const profile = identityHost.__ATOM_IDENTITY_PROFILE;
if (profile !== undefined && profile !== null) {
    installIdentityInMainWorld(profile, installIdentityInWorker.toString());
}
